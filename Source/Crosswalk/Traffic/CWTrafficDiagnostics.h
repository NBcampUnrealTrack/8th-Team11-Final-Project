// CWTrafficDiagnostics.h

#pragma once

#include "CoreMinimal.h"

class AActor;
class ACWBaseVehicle;
class ACWTrafficLane;
class UWorld;

/**
 * 트래픽 파트의 네트워크 진단 로그. 게임플레이 판정은 여기 없다.
 *
 * 왜 따로 두는가
 *   서브시스템은 "앞차가 어디냐 / 정지선이 어디냐 / 누구를 패링하냐" 를 답하는 곳인데,
 *   한때 700줄 중 250줄이 대수 대조·GUID 태그·정지선 미발견 로그였다. 진단은 판정을
 *   바꾸면 안 되는 물건이라("로그를 켜니 증상이 사라진다" 가 되면 실측이 성립하지 않는다)
 *   판정 코드와 같은 파일에 섞여 있으면 그 경계가 눈에 안 보인다.
 *
 * 켜고 끄는 것은 cw.Traffic.* 콘솔 변수다. 기본값이 켜짐인 이유는 .cpp 의 변수 주석 참고.
 * 줄 앞의 [TrafficSync] [TrafficNet] 태그는 그대로 둔다 - 4대 로그를 나란히 놓고 읽는 절차가
 * 태그로 걸러낸다. 카테고리(LogCWTraffic)는 "누가 찍었나", 태그는 "무엇에 관한 줄인가" 다.
 */
namespace CWTrafficDiagnostics
{
	/**
	 * 정지선·신호 동기화 진단 로그를 찍을지. 콘솔 변수 `cw.Traffic.LogSync 0` 으로 끈다.
	 *
	 * 서버와 클라이언트가 같은 사건을 각자 찍으므로, 두 로그를 나란히 놓으면
	 * "서버는 세웠는데 클라는 그냥 지나갔다" 가 줄 단위로 드러난다.
	 * 두 화면을 눈으로 비교해서는 이 판정을 낼 수 없다 - 카메라와 시점이 다르기 때문이다.
	 */
	bool IsSyncLoggingEnabled();

	/** 차량 대수 대조 로그를 찍을지. 콘솔 변수 `cw.Traffic.LogNetCensus 0` 으로 끈다. */
	bool IsNetCensusLoggingEnabled();

	/**
	 * 스폰 순간의 커넥션별 관련성 로그를 찍을지. 콘솔 변수 `cw.Traffic.LogNetRelevancy 0` 으로 끈다.
	 *
	 * 서버에서만 찍는다. 클라이언트는 자기가 왜 그 차를 못 받았는지 알 방법이 없다 -
	 * 관련성 판정은 서버가 커넥션마다 따로 내리고, 탈락한 액터는 아예 보내지지 않는다.
	 */
	bool IsNetRelevancyLoggingEnabled();

	/**
	 * 진단 로그의 역할 표시(서버/클라). 월드의 넷 모드로 정한다.
	 *
	 * 액터의 HasAuthority 로 정하면 안 된다. 복제되지 않는 액터는 클라이언트에서도 권한이
	 * "있음" 이라, 그 기준으로는 클라이언트 줄이 서버 줄로 찍힌다. 예전에는 이 태그가
	 * 두 벌(권한 기준 하나, 넷 모드 기준 하나)이라 같은 세션의 줄이 서로 다른 답을 낼 수 있었다.
	 * 권한 자체가 궁금한 줄(제어기 복제설정)은 그 값을 따로 찍는다.
	 */
	const TCHAR* GetNetRoleTag(const UObject* WorldContextObject);

	/**
	 * 진단 로그의 액터 식별자. 서버와 클라이언트에서 같은 값이 나오는 것을 고른다.
	 *
	 * 액터 이름이 아니라 네트워크 GUID 다. 런타임에 스폰된 차량은 서버와 클라이언트에서
	 * 이름이 다르게 붙어서, 이름으로 찍으면 두 로그를 나란히 놓아도 어느 줄이 같은 차인지
	 * 짚을 수가 없다. 네트워크가 없으면(싱글 PIE) 이름으로 충분하다.
	 */
	FString GetNetIdTag(const AActor* Actor);

	/**
	 * 방금 스폰한 차량이 각 커넥션에 관련 있는지, 그리고 얼마나 떨어져 있는지 찍는다.
	 *
	 * 재는 값은 하나다 - **스폰 지점과 각 클라이언트 시점 사이의 거리, 그리고 차량의 컬 거리.**
	 * 차량은 컬 거리를 따로 정하지 않아 AActor 기본값(15000cm)을 쓰는데, 차선이 그보다 길면
	 * 스폰 순간에는 아무에게도 관련이 없다가 각자 다가올 때 순차로 나타난다. 서 있는 자리가
	 * 사람마다 다르니 이것만으로도 "돌아가면서 한 명만 안 보인다" 가 만들어진다.
	 *
	 * 서버에서만 의미가 있다. 관련성 판정은 서버가 커넥션마다 따로 내리는 값이라,
	 * 탈락한 클라이언트 쪽에는 판정했다는 흔적조차 남지 않는다. 클라이언트 커넥션이
	 * 없는 월드에서는 아무것도 찍지 않는다.
	 *
	 * 차량을 차선 위로 옮겨 놓은 뒤에 불러야 한다. 스폰 직후 위치는 아직 차선 좌표가 아니다.
	 */
	void LogSpawnRelevancy(const ACWBaseVehicle& Vehicle);
}

/**
 * 직전 줄을 기억해야 하는 진단 로그. UCWTrafficSubsystem 이 하나 들고 있다.
 *
 * 대수 대조는 순번과 간격을, 정지선 미발견은 차선별 마지막 사유를 들고 있어야
 * "같은 말을 반복하나" 를 가를 수 있다. 상태가 없는 함수는 위 네임스페이스에 있다.
 */
struct FCWTrafficDiagnostics
{
public:
	/**
	 * 이 화면의 차량 대수를 세 갈래로 나눠 찍는다. 서버·클라이언트 양쪽에서 돈다.
	 *
	 * 트랜스폼을 복제하지 않는 구조라(ACWBaseVehicle 의 네트워크 주석 참고) 클라이언트 화면에
	 * 차가 보이려면 **세 가지가 전부** 성립해야 하고, 셋 중 무엇이 깨져도 증상은 똑같이
	 * "차가 안 보인다" 로 나온다. 눈으로는 갈래를 가를 수 없어서 숫자로 가른다.
	 *
	 *   차량      액터 채널이 이 커넥션에 열렸는가. 서버보다 적으면 관련성이나 대역폭이다
	 *   차선연결  CurrentLane 이 해결됐는가. 적으면 Tick 이 매 프레임 빠져나가 차가 얼어붙는다
	 *   메쉬      VariantPick 의 OnRep 이 돌았는가. 적으면 차는 있는데 투명하다
	 *
	 * 세 숫자가 서버와 모두 같은데도 안 보인다면 네트워크 문제가 아니다. 그 판정 자체가
	 * 이 로그의 산출물이다 - 아니라는 것을 확인하는 데 드는 시간이 제일 아깝다.
	 *
	 * 숫자 뒤에 차량 목록을 네트워크 GUID 로 붙인다. **개수만으로는 갈래가 하나 더 남는다** -
	 * "호스트 2대, 클라 1대" 가 그 차가 아예 안 온 것인지, 늦게 온 것인지, 먼저 사라진
	 * 것인지 구분되지 않는다. 셋은 원인이 다르다(전달 실패 / 채널 개설 지연 / 소멸 전파).
	 * GUID 는 서버와 클라이언트가 같은 값을 가지므로 두 로그의 차량을 한 대씩 짝지어
	 * 생존 구간을 비교할 수 있다.
	 *
	 * 줄 앞에 순번과 **직전 줄로부터 실제로 흐른 시간**을 적는다. 이 로그를 읽는 방식이
	 * "머신마다 한 줄씩 같은 초에 놓고 비교" 인데, 그러려면 양쪽이 같은 간격으로 찍혔다는
	 * 보장이 있어야 한다. 그 보장이 없으면 **"차가 없던 초" 와 "로그가 안 찍힌 초" 가
	 * 구분되지 않아서**, 부하로 프레임이 밀린 클라이언트가 차량을 잃은 것처럼 보인다.
	 * 실제로 PIE 부하 판에서 이 착시로 한 번 오판했다. (수치는 노션 검증 문서)
	 *
	 * 순번은 로그 줄 자체가 유실됐는지, 간격은 타이머가 밀렸는지를 각각 가른다. 둘은
	 * 원인이 다르므로 한 값으로 합칠 수 없다.
	 *
	 * 주기는 1초 고정이고 타이머는 서브시스템이 건다. 4대의 로그를 시각으로 맞춰 읽는
	 * 것이 용도라 주기가 사람마다 다르면 맞춰 볼 수가 없다. 조절할 것은 켜짐 여부뿐이다.
	 */
	void LogVehicleCensus(const UWorld* World, TConstArrayView<TWeakObjectPtr<ACWBaseVehicle>> Vehicles);

	/**
	 * FindActiveStopLine 이 "세울 정지선 없음" 으로 빠져나간 이유를 남긴다.
	 *
	 * 클라이언트에서 차가 정지선을 그냥 지나갈 때, 눈으로는 세 갈래가 구분되지 않는다.
	 * 셋은 고칠 곳이 완전히 다르다.
	 *
	 *   제어기 목록이 비었다   등록이 클라이언트에서 안 돌았다
	 *   통행 신호라고 답한다   제어기는 있는데 GroupStates 가 안 왔다 (기본색으로 답하는 중)
	 *   정지선 목록이 비었다   정지선 액터 등록 문제
	 *
	 * 값이 바뀔 때만 찍는다. 초당 한 줄로 조이는 것으로는 부족했다 - 미발견 사유의 대부분은
	 * "제어기가 통행 신호라고 답함" 인데 이건 정상 상태라 파란불 길이만큼 똑같은 줄이 쌓인다.
	 * 09-16 로그에서 938줄이 나왔고 그중 읽을 값이 있는 줄은 몇 줄뿐이었다.
	 *
	 * **직전 한 줄이 아니라 차선별로 비교한다.** 이 판정은 차량마다 매 틱 들어오고,
	 * 차량들이 서로 다른 차선을 물고 번갈아 부른다. 마지막 한 벌만 들고 있으면 A-B-A-B 로
	 * 갈릴 때 직전 호출과 같은 경우가 사실상 없어서 억제가 통째로 무력해진다.
	 * 09-17 세션에서 그렇게 새어 나간 줄이 서버 한 대에만 473,890 개였다.
	 *
	 * @param DirectorCount  등록된 제어기 수. 이유 문자열만으로는 "통행이라 답했다" 와
	 *                       "제어기 자체가 없다" 가 같은 줄로 보일 수 있어 개수를 같이 찍는다.
	 */
	void LogStopLineMiss(const UWorld* World, const ACWTrafficLane* Lane, const TCHAR* Reason, int32 DirectorCount, int32 StopLineCount);

private:
	/** 대수 대조 줄의 순번. 로그 줄이 통째로 유실됐는지 보는 값이다. */
	int32 CensusSequence = 0;

	/**
	 * 직전 대조를 찍은 실제 시각. 월드 시간이 아니라 벽시계다 -
	 * 이 값과 맞춰 볼 상대가 로그 타임스탬프이기 때문이다.
	 */
	double LastCensusRealTime = -1.0;

	/**
	 * 차선별로 마지막에 찍은 정지선 미발견 사유. 같은 말을 반복하지 않는 데만 쓴다.
	 *
	 * 사유를 포인터가 아니라 문자열로 들고 있는 이유: 넘어오는 값이 전부 리터럴이라
	 * 대개는 포인터 비교로도 맞지만, 리터럴을 한 곳에 모아 준다는 보장이 표준에 없다.
	 */
	TMap<FName, FString> LastStopLineMissReasonByLane;
};
